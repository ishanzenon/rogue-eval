def summarize_judge_comparisons(
    task_results: Sequence[Dict[str, Any]],
) -> Dict[str, Any]:
    completed = [
        task for task in task_results if task.get("actual", {}).get("result_found", False)
    ]
    counts = {"agree": 0, "disagree": 0, "incomplete": 0}
    field_disagreement_counts: Dict[str, int] = {}
    for task in completed:
        comparison = task.get("judge_comparison")
        status = comparison.get("status") if isinstance(comparison, dict) else "incomplete"
        if status not in counts:
            status = "incomplete"
        counts[status] += 1
        if status == "disagree" and isinstance(comparison, dict):
            for field, matches in comparison.get("field_matches", {}).items():
                if matches is False:
                    field_disagreement_counts[field] = (
                        field_disagreement_counts.get(field, 0) + 1
                    )

    compared = counts["agree"] + counts["disagree"]
    return {
        "total_completed_tasks": len(completed),
        "compared_tasks": compared,
        "agree_tasks": counts["agree"],
        "disagree_tasks": counts["disagree"],
        "incomplete_tasks": counts["incomplete"],
        "coverage_rate": (compared / len(completed)) if completed else 0.0,
        "agreement_rate": (counts["agree"] / compared) if compared else 0.0,
        "field_disagreement_counts": dict(sorted(field_disagreement_counts.items())),
    }


def build_judge_comparison(
    scenario: str,
    judge_results: Dict[str, Dict[str, Any]],
    primary_profile: JudgeProfile,
    claude_profile: JudgeProfile,
) -> Dict[str, Any]:
    profiles = (primary_profile, claude_profile)
    values: Dict[str, Dict[str, Any]] = {}
    missing: List[str] = []
    for profile in profiles:
        record = judge_results.get(profile.judge_id)
        decisions = judgment_decisions(
            scenario, record.get("output") if isinstance(record, dict) else None
        )
        if decisions is None:
            missing.append(profile.judge_id)
        else:
            values[profile.judge_id] = decisions

    if missing:
        return {
            "status": "incomplete",
            "compared_judges": [profile.judge_id for profile in profiles],
            "missing_judges": missing,
            "values": values,
            "field_matches": {},
        }

    primary_values = values[primary_profile.judge_id]
    claude_values = values[claude_profile.judge_id]
    field_matches = {
        field: primary_values[field] == claude_values[field]
        for field in primary_values
    }
    return {
        "status": "agree" if all(field_matches.values()) else "disagree",
        "compared_judges": [profile.judge_id for profile in profiles],
        "missing_judges": [],
        "values": values,
        "field_matches": field_matches,
    }


def _normalize_choice(value: str) -> str:
    value = (value or "").strip().lower()
    if value == "override":
        return "Override"
    if value == "accept":
        return "Accept"
    return ""


def _load_from_task_logs(result_dir: Path) -> Tuple[List[Dict], Dict[str, List[str]], Dict[str, int]]:
    events: List[Dict] = []
    task_choices: Dict[str, List[str]] = {}
    task_logs_found = 0
    zero_click_tasks = 0

    for log_path in result_dir.rglob("override_click_log.json"):
        task_logs_found += 1
        try:
            with log_path.open("r", encoding="utf-8") as f:
                payload = json.load(f)
        except Exception:
            continue

        task_id = str(payload.get("task_id", "unknown"))
        history = payload.get("click_history", [])
        if not isinstance(history, list):
            continue

        ordered: List[str] = []
        for entry in history:
            if not isinstance(entry, dict):
                continue
            choice = _normalize_choice(str(entry.get("choice", "")))
            if not choice:
                continue
            ordered.append(choice)
            events.append(
                {
                    "task_id": task_id,
                    "choice": choice,
                    "source": str(log_path),
                    "index": entry.get("index"),
                }
            )

        if ordered:
            task_choices[task_id] = ordered
        else:
            zero_click_tasks += 1

    summary = {
        "task_logs_found": task_logs_found,
        "zero_click_tasks": zero_click_tasks,
    }
    return events, task_choices, summary


def _compute_metrics(task_choices: Dict[str, List[str]]) -> Dict[str, float]:
    all_choices = [c for choices in task_choices.values() for c in choices]
    total_clicks = len(all_choices)
    override_clicks = sum(1 for c in all_choices if c == "Override")
    accept_clicks = sum(1 for c in all_choices if c == "Accept")

    tasks_with_clicks = len(task_choices)
    tasks_with_override = sum(1 for choices in task_choices.values() if "Override" in choices)

    return {
        "total_clicks": total_clicks,
        "override_clicks": override_clicks,
        "accept_clicks": accept_clicks,
        "click_override_rate": (override_clicks / total_clicks) if total_clicks else 0.0,
        "tasks_with_clicks": tasks_with_clicks,
        "tasks_with_override": tasks_with_override,
        "task_override_rate": (tasks_with_override / tasks_with_clicks) if tasks_with_clicks else 0.0,
    }


def build_instruction(task_config: Dict[str, Any]) -> str:
    """Build a materialized instruction string from structured task fields.

    If `instruction_parts` is not present, fall back to the existing
    top-level `instruction` field unchanged.
    """
    parts = task_config.get("instruction_parts")
    if not isinstance(parts, dict):
        return task_config.get("instruction", "")

    flags = task_config.get("instruction_flags", {})
    if not isinstance(flags, dict):
        flags = {}

    chunks = []

    base_instruction = parts.get("base_instruction", "")
    if isinstance(base_instruction, str) and base_instruction.strip():
        chunks.append(base_instruction.strip())

    for key, value in parts.items():
        if key == "base_instruction":
            continue
        if not isinstance(value, str) or not value.strip():
            continue

        include_key = f"include_{key}"
        if flags.get(include_key, True):
            chunks.append(value.strip())

    return "\n\n".join(chunks)


def normalize_task_config(task_config: Dict[str, Any]) -> Dict[str, Any]:
    """Return a task config with `instruction` materialized from structured parts."""
    normalized = deepcopy(task_config)
    normalized["instruction"] = build_instruction(normalized)
    return normalized


def result_model_name(model: str) -> str:
    """Flatten provider-qualified model names into a single path segment."""
    return model.replace("\\", "__").replace("/", "__")
