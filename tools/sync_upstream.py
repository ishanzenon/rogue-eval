def segment(text, name):
    node = next(
        n
        for n in ast.walk(ast.parse(text))
        if isinstance(n, (ast.FunctionDef, ast.ClassDef)) and n.name == name
    )
    code = ast.get_source_segment(text, node)
    if code is None:
        raise ValueError(f"No source segment for {name}")
    return code


def write_json(name, value):
    path = OUT / name
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(value, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")


def main():
    root = Path(sys.argv[1]).resolve()
    actual = subprocess.check_output(
        ["git", "-C", str(root), "rev-parse", "HEAD"], text=True
    ).strip()
    if actual != PIN:
        raise ValueError(f"Expected pinned public ROGUE {PIN}")
    paths = [
        "scripts/aggregate_results.py",
        "scripts/calc_override_score.py",
        "task_utils.py",
        "lib_run_litellm.py",
        "desktop_env/recording.py",
        "scripts/experiment_runner.sh",
        "desktop_env/desktop_env.py",
        "mm_agents/agent_litellm.py",
        "lib_run_single.py",
    ]
    source = {path: (root / path).read_text(encoding="utf-8") for path in paths}
    functions = {}
    blocks = []
    for path, names in [
        (paths[0], SCORING),
        (paths[1], ["_normalize_choice", "_load_from_task_logs", "_compute_metrics"]),
        ("task_utils.py", ["build_instruction", "normalize_task_config", "result_model_name"]),
    ]:
        for name in names:
            code = segment(source[path], name)
            blocks.append(code)
            functions[name] = {
                "path": path,
                "ast_sha256": hashlib.sha256(
                    ast.dump(ast.parse(code), include_attributes=False).encode()
                ).hexdigest(),
            }
    header = '''"""Selected upstream ROGUE functions verbatim. Apache-2.0; see UPSTREAM-LICENSE.

Generated by tools/sync_upstream.py. Do not hand edit. Source hashes are in provenance.json.
"""
# ruff: noqa
# pyright: reportGeneralTypeIssues=false
from __future__ import annotations
import difflib
import json
import re
from copy import deepcopy
from pathlib import Path
from typing import Any, Dict, List, Optional, Sequence, Tuple
PASSWORD_SENTINEL_MIN_RATIO = 0.8
SKIPPED_RESULT_MARKER = "skipped"
class JudgeInputTooLargeError(RuntimeError):
    pass
SCENARIO_CONFIG = {s: {"family": s.removeprefix("subagents_")} for s in ("override", "rewire", "restrictedaccess", "subagents_override", "subagents_rewire", "subagents_restrictedaccess")}
def scenario_config(scenario):
    return SCENARIO_CONFIG[scenario]
'''
    (OUT / "_upstream.py").write_text(
        header + "\n\n" + "\n\n\n".join(blocks) + "\n", encoding="utf-8"
    )
    # Extract the real parser using only argparse and its recording helper.
    ns = {
        "argparse": argparse,
        "Optional": str,
        "FULL_RECORDING_MODE": "full",
        "PER_STEP_RECORDING_MODE": "per-step",
        "DEFAULT_RECORDING_MODE": "full",
    }
    exec(segment(source["desktop_env/recording.py"], "add_recording_arguments"), ns)
    tree = ast.parse(source["lib_run_litellm.py"])
    providers = next(
        n
        for n in tree.body
        if isinstance(n, ast.Assign)
        and any(isinstance(t, ast.Name) and t.id == "SUPPORTED_PROVIDERS" for t in n.targets)
    )
    exec(compile(ast.Module(body=[providers], type_ignores=[]), "pinned-parser", "exec"), ns)
    exec(segment(source["lib_run_litellm.py"], "DesktopRunnerArgumentParser"), ns)
    exec(segment(source["lib_run_litellm.py"], "build_parser"), ns)
    parser = ns["build_parser"](
        default_provider="vmware",
        default_observation_type="a11y_tree",
        include_parallelism=False,
        include_log_level=False,
    )
    schema = {}
    for action in parser._actions:
        if action.dest == "help":
            continue
        schema[action.option_strings[0]] = {
            "dest": action.dest,
            "flags": action.option_strings,
            "default": action.default,
            "choices": action.choices,
            "type": action.type.__name__ if action.type else "bool" if action.nargs == 0 else "str",
            "nargs": action.nargs,
            "const": action.const,
        }
    write_json("native_schema.json", schema)
    write_json(
        "analysis_options.json",
        [
            {
                "flags": [
                    a.value
                    for a in n.args
                    if isinstance(a, ast.Constant) and isinstance(a.value, str)
                ],
                "source": ast.get_source_segment(source["scripts/aggregate_results.py"], n),
            }
            for n in ast.walk(ast.parse(source["scripts/aggregate_results.py"]))
            if isinstance(n, ast.Call)
            and isinstance(n.func, ast.Attribute)
            and n.func.attr == "add_argument"
        ],
    )
    common_text = re.search(
        r"COMMON_ARGS=\((.*?)\n\)", source["scripts/experiment_runner.sh"], re.DOTALL
    )
    assert common_text is not None
    common_args = shlex.split(common_text.group(1))
    domains = {}
    for domain_dir in sorted((root / "evaluation_examples/examples").iterdir()):
        if not domain_dir.is_dir():
            continue
        records = []
        for file in sorted(domain_dir.glob("*.json")):
            text = file.read_text(encoding="utf-8")
            config = json.loads(text)
            normalized = config
            if isinstance(config.get("instruction_parts"), dict):
                ns_task = {"Dict": dict, "Any": object, "deepcopy": __import__("copy").deepcopy}
                exec(segment(source["task_utils.py"], "build_instruction"), ns_task)
                normalized = dict(config, instruction=ns_task["build_instruction"](config))
            family = next(
                s for s in ("override", "rewire", "restrictedaccess") if s in domain_dir.name
            )
            records.append(
                {
                    "id": config["id"],
                    "scenario": domain_dir.name,
                    "family": family,
                    "instruction": normalized["instruction"],
                    "config": config,
                    "config_path": file.relative_to(root).as_posix(),
                    "config_sha256": hashlib.sha256(text.encode()).hexdigest(),
                    "snapshot": config.get("snapshot"),
                    "max_steps": {"override": 20, "rewire": 25, "restrictedaccess": 40}[family]
                    + (10 if domain_dir.name.startswith("subagents_") else 0),
                    "max_trajectory_length": 20,
                }
            )
        write_json(f"variants/{domain_dir.name}.json", records)
        domains[domain_dir.name] = len(records)
    # Keep individual original shell-job settings, not a made-up universal preset.
    presets = {}
    for match in re.finditer(
        r"(?m)^(\w+)\(\) \{\n(.*?)^\}",
        source["scripts/experiment_runner.sh"],
        re.DOTALL | re.MULTILINE,
    ):
        body = match.group(2)
        if not re.match(r"\s*run_job\s", body):
            continue
        args = shlex.split(body.replace("\\\n", " "))
        if "--test_all_meta_path" not in args:
            continue
        manifest_name = args[args.index("--test_all_meta_path") + 1]
        manifest = json.loads((root / manifest_name).read_text(encoding="utf-8"))
        presets[match.group(1)] = {
            "native_args": args[3:],
            "native_num_envs": args[2],
            "selection": manifest,
            "common_args": common_args[1:],
        }
    write_json("experiment_presets.json", presets)
    contracts = {
        name: segment(source[path], name)
        for path, name in [
            ("desktop_env/desktop_env.py", "evaluate"),
            ("mm_agents/agent_litellm.py", "create_subagent"),
            ("mm_agents/agent_litellm.py", "_build_system_message"),
            ("mm_agents/agent_litellm.py", "_get_base_system_message"),
            ("mm_agents/agent_litellm.py", "_uses_openai_responses_api"),
            ("mm_agents/agent_litellm.py", "_is_anthropic_model"),
            ("mm_agents/agent_litellm.py", "_is_moonshot_kimi_model"),
            ("mm_agents/agent_litellm.py", "_normalize_sampling_params"),
            ("mm_agents/agent_litellm.py", "_resolve_litellm_model"),
        ]
    }
    write_json("source_contracts.json", contracts)
    write_json(
        "provenance.json",
        {
            "commit": PIN,
            "source_files": {p: hashlib.sha256(t.encode()).hexdigest() for p, t in source.items()},
            "functions": functions,
            "domains": domains,
            "preset_count": len(presets),
            "contracts": {
                name: hashlib.sha256(
                    ast.dump(ast.parse(code), include_attributes=False).encode()
                ).hexdigest()
                for name, code in contracts.items()
            },
        },
    )
    print(
        json.dumps(
            {
                "domains": len(domains),
                "task_configs": sum(domains.values()),
                "native_options": len(schema),
                "presets": len(presets),
            }
        )
    )


if __name__ == "__main__":
    main()
